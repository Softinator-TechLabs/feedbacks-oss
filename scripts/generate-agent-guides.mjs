import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";
const root = new URL("../", import.meta.url);
const topics = {
  start: "SKILL.md",
  glossary: "references/glossary.md",
  media: "references/media.md",
  workflow: "references/workflow.md",
  install: "references/install.md",
  "manage-context": "../manage-feedbacks-context/SKILL.md",
};
const guides = {};
for (const [topic, path] of Object.entries(topics))
  guides[topic] = {
    path: topic === "manage-context" ? "SKILL.md" : path,
    skill: topic === "manage-context" ? "manage-feedbacks-context" : "review-feedback",
    content: await readFile(
      new URL(`plugins/feedbacks/skills/review-feedback/${path}`, root),
      "utf8",
    ),
  };
const output = await format(
  `// Generated by scripts/generate-agent-guides.mjs; edit the portable skill instead.\nexport const agentGuides = ${JSON.stringify(guides, null, 2)} as const;\n`,
  { parser: "typescript", printWidth: 90, trailingComma: "all" },
);
const target = new URL("src/shared/agent-guides.generated.ts", root);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error("Agent guides are stale; run npm run docs:generate");
} else await writeFile(target, output);
